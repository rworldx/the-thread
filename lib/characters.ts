  /* Carries a film alone, and each is top-fifteen somewhere. */
  "deadpool", "black-panther", "doctor-strange", "loki", "black-widow",
  "thanos", "venom", "scarlet-witch", "groot", "star-lord", "hawkeye",
  "winter-soldier", "nick-fury", "captain-marvel",
  /* Household names from the comics as much as the films. */
  "magneto", "professor-x", "doctor-doom", "green-goblin", "daredevil",
  "punisher", "ant-man", "rocket", "gamora", "vision", "falcon", "war-machine",
  /* The X-Men and Fantastic Four benches, and the street level. */
  "jean-grey", "cyclops", "storm", "mystique", "kingpin", "she-hulk",
