const FAME_RANK = new Map(FAME.map((id, i) => [id, i]));

export const shownCharacters: Character[] = [...allCharacters].sort((a, b) => {
  const ra = FAME_RANK.get(a.id) ?? Infinity;
  const rb = FAME_RANK.get(b.id) ?? Infinity;
  if (ra !== rb) return ra - rb;
  if (a.appearances.length !== b.appearances.length) {
    return b.appearances.length - a.appearances.length;
  }
  return a.nameEn.localeCompare(b.nameEn);
});

/** Has this character ever been credited in anything the corpus holds? */
export function isOnScreen(c: Character): boolean {
  return c.appearances.length > 0;
}

/**
 * Characters credited in a title, IN BILLING ORDER.
 *
 * This used to return them in the corpus's own order, which is the order they
 * happen to be written in `content/characters.ts` — so a Spider-Man film led
 * with Doctor Strange, and every title led with whoever was typed first years
 * ago. On a section headed "who is in this", the answer has to start with
 * whoever the film is about.
 *
 * The film already states that. TMDB's cast list is ordered by billing, and
 * billing is the studio's own answer to "who is this about" — so the lead of
 * every title leads here, with no per-title rule and nothing to keep in sync.
 *
 * A PERFORMANCE inherits the position of the credit naming its own actor,
 * which is what puts the three Peters of No Way Home in the order the poster
 * puts them rather than in corpus order.
 */
export function charactersIn(titleId: string): Character[] {
  const credits = castOf(titleId);

  const rank = new Map<string, number>();
  credits.forEach((credit, i) => {
    for (const seg of segments(credit.character)) {
      for (const id of aliasIndex.get(seg) ?? []) {
        if (!rank.has(id)) rank.set(id, i);
      }
    }
  });
  /* Performances carry no aliases, so they match no credit by name. They take
     the position of the credit their PERFORMER is billed at. */
  for (const c of allCharacters) {
    if (!c.performerOf) continue;
    const i = credits.findIndex((x) => x.actor === c.performerOf!.actor);
    if (i >= 0) rank.set(c.id, i);
  }

  /**
   * A CAMEO GOES LAST, whatever the billing says.
   *
   * Stan Lee is billed 4th in Thor and 60th in Endgame, so ordering purely by
   * credit position put him near the top of some films and the bottom of
   * others — arbitrary, and on a section headed "who is in this" it puts a
   * walk-on above the lead. He is in 44 titles and is the lead of none.
   */
  const cameo = (c: Character) => (c.creditedActor !== null ? 1 : 0);

  return allCharacters
    .filter((c) => c.appearances.includes(titleId))
    .sort(
      (a, b) =>
        cameo(a) - cameo(b) ||
        (rank.get(a.id) ?? 1e6) - (rank.get(b.id) ?? 1e6),
    );
}

